#!/bin/sh
# Deterministic test environment (issue #9).
#
# Builds a fresh, canonical database and serves it on an isolated port so the
# suites run against known ids instead of whatever the dev board happens to
# point at.
#
#   database : $RETROBB_TEST_DB   (default retrobb_test — RECREATED each run)
#   port     : $RETROBB_TEST_PORT (default 8081)
#   fixture  : bin/migrate.php --seed  -> admin/PixelMod/dialup_dan/Guest_2003,
#              categories/forums/topics at fixed ids 1..N
#
# Never touches retrobb_live (user data), retrobb (scratch) or the dev board
# on :8080. Idempotent: re-running drops and rebuilds retrobb_test.
set -e
ROOT="$(pwd)"
PORT="${RETROBB_TEST_PORT:-8081}"
DB="${RETROBB_TEST_DB:-retrobb_test}"
CFG="${ROOT}/storage/test-config.php"

# Run from the repo root. (Do NOT require config.php — it is gitignored, so a
# fresh CI checkout has none; the test board gets its own generated config.)
if [ ! -f "${ROOT}/bin/migrate.php" ]; then
    echo "testenv: run this from the repo root (no bin/migrate.php here)" >&2
    exit 2
fi

mkdir -p "${ROOT}/storage"
cat > "$CFG" <<PHP
<?php
declare(strict_types=1);
// Generated by scripts/testenv.sh — test board config. Not for real boards.
return [
    'mysql_host' => 'retrobb-mysql',
    'mysql_port' => 3306,
    'mysql_db' => '$DB',
    'mysql_user' => 'retrobb',
    'mysql_pass' => 'retrobb',
];
PHP

# MySQL must be up (starts the container if needed).
sh scripts/mysql-up.sh >/dev/null 2>&1 || true
if ! docker exec retrobb-mysql mysqladmin ping -h127.0.0.1 -uroot -proot --silent 2>/dev/null; then
    echo "testenv: mysql is not reachable (run scripts/mysql-up.sh)" >&2
    exit 2
fi

echo "testenv: rebuilding database ${DB}…"
docker exec retrobb-mysql mysql -uroot -proot -e \
  "DROP DATABASE IF EXISTS \`${DB}\`; CREATE DATABASE \`${DB}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci; GRANT ALL ON \`${DB}\`.* TO 'retrobb'@'%'; FLUSH PRIVILEGES;" 2>/dev/null

echo "testenv: migrate + seed…"
docker run --rm -v "${ROOT}:/app" -v "${CFG}:/app/config.php" -w /app --network retrobb-net \
  retrobb-php php bin/migrate.php --seed | tail -2

echo "testenv: starting board on :${PORT}…"
docker rm -f retrobb-test >/dev/null 2>&1 || true
docker run -d --rm --name retrobb-test -p "${PORT}:8000" \
  -v "${ROOT}:/app" -v "${CFG}:/app/config.php" -w /app --network retrobb-net \
  retrobb-php php -S 0.0.0.0:8000 -t public public/router.php >/dev/null

for i in $(seq 1 20); do
    if curl -sf -o /dev/null "http://localhost:${PORT}/login"; then break; fi
    sleep 0.5
done

echo
echo "testenv ready"
echo "  board : http://localhost:${PORT}"
echo "  db    : ${DB}"
echo "  run   : RETROBB_TEST_BASE=http://localhost:${PORT} RETROBB_TEST_DB=${DB} python3 scripts/runtests.py"
